export const supportedExtensionLanguages = [
  'tr',
  'en',
  'de',
  'es',
  'fr',
  'it',
  'pt',
  'ru',
  'zh',
  'ja',
  'ko',
  'ar',
] as const;

export type ExtensionLanguage = (typeof supportedExtensionLanguages)[number];

export const extensionLanguageLabels: Record<ExtensionLanguage, string> = {
  tr: 'TR',
  en: 'EN',
  de: 'DE',
  es: 'ES',
  fr: 'FR',
  it: 'IT',
  pt: 'PT',
  ru: 'RU',
  zh: 'ZH',
  ja: 'JA',
  ko: 'KO',
  ar: 'AR',
};

let memoryLangStorage: string | null = null;

export function getPreferredLanguage(): ExtensionLanguage {
  let saved: string | null = null;
  try {
    if (typeof localStorage !== 'undefined') {
      saved = localStorage.getItem('aegis-extension-language');
    }
  } catch {
    saved = memoryLangStorage;
  }
  if (!saved) {
    saved = memoryLangStorage;
  }

  if (saved && (supportedExtensionLanguages as readonly string[]).includes(saved)) {
    return saved as ExtensionLanguage;
  }
  
  try {
    if (typeof navigator !== 'undefined' && navigator.language) {
      const browserLang = navigator.language.substring(0, 2).toLowerCase() as ExtensionLanguage;
      if ((supportedExtensionLanguages as readonly string[]).includes(browserLang)) {
        return browserLang;
      }
    }
  } catch {
    // fallback
  }
  return 'tr';
}

export function savePreferredLanguage(lang: ExtensionLanguage): void {
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('aegis-extension-language', lang);
    }
  } catch {
    // ignore
  }
  memoryLangStorage = lang;
}

export function translate(key: keyof typeof extensionTranslations['en'], lang?: ExtensionLanguage): string {
  const currentLang = lang || getPreferredLanguage();
  const dict = extensionTranslations[currentLang] || extensionTranslations['en'];
  return (dict as any)[key] || extensionTranslations['en'][key] || key;
}
