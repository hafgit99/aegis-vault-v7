/**
 * @file scripts/android-gradle-glue.cjs
 * @description Writes the Tauri-generated Gradle glue that a bare `./gradlew`
 * invocation needs and that the Tauri CLI only writes as a side effect of a
 * full mobile build.
 *
 * ## Why this exists
 *
 * `settings.gradle` ends with `apply from: 'tauri.settings.gradle'`, and
 * `app/build.gradle.kts` ends with `apply(from = "tauri.build.gradle.kts")`.
 * Both of those files are gitignored and neither is tracked — correctly: they
 * contain absolute cargo-registry paths (`C:\Users\<name>\.cargo\registry\...`),
 * so committing them would both leak a username and break every machine but
 * the author's.
 *
 * The cost is that a clean checkout cannot configure Gradle at all:
 *
 *   > A problem occurred evaluating settings 'android'.
 *   > Could not read script '.../tauri.settings.gradle' as it does not exist.
 *
 * Every developer hits `tauri android build`/`dev`/`run` instead, and those
 * write the glue on their way past (`inject_tauri_settings`). So the release
 * workflow never sees this, and a bare `./gradlew` always does.
 *
 * ## Why not `tauri android init`
 *
 * Because it does not write them either. Verified on this repository, with the
 * two files deleted: `npm run android:init` prints "Project generated
 * successfully!" in ~10s and creates neither. `init` only scaffolds a project
 * that does not exist yet; the glue is a build-time side effect it never
 * performs. The remaining CLI options are `build`/`dev`/`run`, all of which mean
 * compiling the Rust library for three Android ABIs with the NDK — minutes of
 * work, and a completely different (and much more failure-prone) job than
 * "lint the Kotlin".
 *
 * ## What it writes, and how it stays honest
 *
 * The two files are pure function of the cargo registry contents, so this
 * script reproduces them from `Cargo.lock` plus the unpacked crate sources:
 *
 *   - `tauri.settings.gradle`      — one `include`/projectDir pair per crate
 *                                    that has an `android/` directory
 *   - `app/tauri.build.gradle.kts` — the same list as project dependencies
 *
 * The "has an `android/` directory" rule is not a guess: it is what the CLI
 * does, and it is observable here. `Cargo.toml` depends on `tauri-plugin-log`
 * and `tauri-plugin-updater`, and the CLI includes neither in
 * `tauri.settings.gradle` — neither ships Android code. Only
 * `tauri-plugin-biometric` does.
 *
 * The set is read from `Cargo.lock`, not from a hardcoded list, so adding a
 * mobile plugin cannot silently drop it out of what CI lints. Versions come
 * from the lock too, because the registry can hold several (this machine has
 * both `tauri-plugin-biometric-2.3.2` and `-2.3.3`).
 *
 * Drift from the CLI is possible in principle: if a future Tauri release adds a
 * line to the generated files, this script will not know. That fails loudly —
 * the app module will fail to compile for want of a symbol, and the lint step
 * goes red rather than quietly linting less. It cannot fail silently.
 *
 * Exits 0 on success, 1 if any required crate cannot be found.
 *
 * @license SPDX-License-Identifier: Apache-2.0
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { pass, failExit } = require('./release-utils.cjs');

const repoRoot = path.resolve(__dirname, '..');
const androidDir = path.join(repoRoot, 'src-tauri', 'gen', 'android');
const cargoLockPath = path.join(repoRoot, 'src-tauri', 'Cargo.lock');
const settingsPath = path.join(androidDir, 'settings.gradle');
const appBuildPath = path.join(androidDir, 'app', 'build.gradle.kts');
const tauriSettingsPath = path.join(androidDir, 'tauri.settings.gradle');
const appGluePath = path.join(androidDir, 'app', 'tauri.build.gradle.kts');

const GENERATED_HEADER = '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.';

/**
 * `failExit` from release-utils only records a failure; it does not stop the
 * process. Every guard here is "do not write the file", so each one has to
 * leave immediately — otherwise a script that just reported a hard error goes
 * on to write the very file the error was about.
 */
function abort(message) {
  failExit(message);
  process.exit(1);
}

/**
 * How a crate maps onto a Gradle project.
 *
 * Not uniform, and the asymmetry is not guessable from the crate layout alone:
 *
 *   tauri                 -> :tauri-android, <crate>/mobile/android
 *   tauri-plugin-<name>   -> :tauri-plugin-<name>, <crate>/android
 *
 * The core library's Gradle module is named `tauri-android` (Tauri declares
 * that name itself; it is not the crate name), and its Android sources live
 * under `mobile/`, while a plugin's live at the crate root under the crate's own
 * name. Both are taken from what the Tauri CLI actually generated in this
 * repository, not inferred.
 */
function gradleProjectFor(crate) {
  if (crate.name === 'tauri') {
    return { project: ':tauri-android', subdirs: ['mobile/android', 'android'] };
  }
  return { project: `:${crate.name}`, subdirs: ['android', 'mobile/android'] };
}


/**
 * Reads every `name`/`version` pair out of a `Cargo.lock`.
 *
 * Only the two keys this script needs are extracted, from the `[[package]]`
 * blocks. A full TOML parser is not worth a dependency here: Cargo.lock has one
 * shape, and a regex that fails to match yields an empty crate list, which the
 * caller's assertions below turn into a hard error rather than a wrong file.
 */
function readLockedCrates(lockText) {
  const crates = [];
  const blocks = lockText.split(/\[\[package\]\]/).slice(1);
  for (const block of blocks) {
    const name = /\nname\s*=\s*"([^"]+)"/.exec(`\n${block}`);
    const version = /\nversion\s*=\s*"([^"]+)"/.exec(`\n${block}`);
    if (name && version) crates.push({ name: name[1], version: version[1] });
  }
  return crates;
}

/**
 * Every unpacked crate directory under `$CARGO_HOME/registry/src/*`.
 *
 * A flat map of `<name>-<version>` to absolute path. There is usually more than
 * one registry hash directory (crates.io, git dependencies), so all of them are
 * searched rather than assuming the first.
 */
function readRegistryCrates() {
  const cargoHome = process.env.CARGO_HOME || path.join(os.homedir(), '.cargo');
  const srcRoot = path.join(cargoHome, 'registry', 'src');
  const found = new Map();

  let registryDirs = [];
  try {
    registryDirs = fs.readdirSync(srcRoot, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => path.join(srcRoot, entry.name));
  } catch (_) {
    return { found, srcRoot };
  }

  for (const registryDir of registryDirs) {
    let entries = [];
    try {
      entries = fs.readdirSync(registryDir, { withFileTypes: true });
    } catch (_) {
      continue;
    }
    for (const entry of entries) {
      if (!entry.isDirectory()) continue;
      const key = entry.name;
      // First registry wins; with a single crates.io hash there is no choice to
      // make, and a duplicate across hashes is not a case worth failing on.
      if (!found.has(key)) found.set(key, path.join(registryDir, entry.name));
    }
  }

  return { found, srcRoot };
}

/** Groovy string literal escaping: a literal backslash must be doubled. */
function groovyPath(absolutePath) {
  return absolutePath.replace(/\\/g, '\\\\');
}

function main() {
  // The glue is only meaningful if the tracked files still apply it. If either
  // apply line disappears, writing the glue is pointless and the real cause is
  // somewhere else — say so instead of creating two orphan files.
  const settings = fs.readFileSync(settingsPath, 'utf8');
  if (!/tauri\.settings\.gradle/.test(settings)) {
    abort(`settings.gradle no longer applies tauri.settings.gradle; ${path.relative(repoRoot, settingsPath)} must be changed before this script is useful`);
  }
  const appBuild = fs.readFileSync(appBuildPath, 'utf8');
  if (!/tauri\.build\.gradle\.kts/.test(appBuild)) {
    abort(`app/build.gradle.kts no longer applies tauri.build.gradle.kts; ${path.relative(repoRoot, appBuildPath)} must be changed before this script is useful`);
  }

  const locked = readLockedCrates(fs.readFileSync(cargoLockPath, 'utf8'));
  if (locked.length === 0) {
    abort(`no [[package]] entries parsed from ${path.relative(repoRoot, cargoLockPath)}; refusing to write an empty Gradle configuration`);
  }

  const { found, srcRoot } = readRegistryCrates();
  if (found.size === 0) {
    abort(
      `no unpacked crates under ${srcRoot}. The tauri crates must be present before the Gradle glue can point at them — run \`cargo fetch --locked\` in src-tauri first.`,
    );
  }

  // `tauri` first (it is the module the app is built around), then the mobile
  // plugins in a stable order so the generated file does not churn.
  const candidates = locked
    .filter((crate) => crate.name === 'tauri' || crate.name.startsWith('tauri-plugin-'))
    .sort((a, b) => (a.name === 'tauri' ? -1 : b.name === 'tauri' ? 1 : a.name.localeCompare(b.name)));

  const projects = [];
  const notUnpacked = [];
  const noAndroidDir = [];

  for (const crate of candidates) {
    const crateDir = found.get(`${crate.name}-${crate.version}`);
    if (!crateDir) {
      // Not unpacked is only a problem if the crate ships Android code, and that
      // cannot be known without the sources. Recorded and reported, not fatal on
      // its own — but never silent, because a mobile plugin missing from the glue
      // is exactly what would make CI lint less than the release build.
      notUnpacked.push(`${crate.name}-${crate.version}`);
      continue;
    }
    const { project, subdirs } = gradleProjectFor(crate);
    const androidDirForProject = subdirs
      .map((subdir) => path.join(crateDir, ...subdir.split('/')))
      .find((candidate) => fs.existsSync(candidate));
    if (!androidDirForProject) {
      noAndroidDir.push(`${crate.name}-${crate.version} (looked for ${subdirs.join(' and ')})`);
      continue;
    }
    projects.push({ name: crate.name, project, dir: androidDirForProject });
  }

  if (!projects.some((project) => project.name === 'tauri')) {
    abort(
      `the tauri crate's Android sources were not found in the cargo registry (looked under ${srcRoot}, `
      + `and for every locked tauri version: ${noAndroidDir.join('; ') || 'none'}). `
      + `Run \`cargo fetch --locked\` in src-tauri.`,
    );
  }

  const settingsLines = [GENERATED_HEADER];
  for (const project of projects) {
    settingsLines.push(`include '${project.project}'`);
    settingsLines.push(`project('${project.project}').projectDir = new File("${groovyPath(project.dir)}")`);
  }

  const appLines = [
    GENERATED_HEADER,
    // The CLI also adds `androidx.lifecycle:lifecycle-process` here. It is
    // already declared in app/build.gradle.kts, so repeating it here would only
    // pin a second version that nothing reads.
    'val implementation by configurations',
    'dependencies {',
    ...projects.map((project) => `  implementation(project("${project.project}"))`),
    '}',
  ];

  fs.writeFileSync(tauriSettingsPath, `${settingsLines.join('\n')}\n`);
  fs.writeFileSync(appGluePath, `${appLines.join('\n')}\n`);

  pass(`wrote ${path.relative(repoRoot, tauriSettingsPath)} with ${projects.length} Gradle project(s)`);
  for (const project of projects) {
    console.log(`  ${project.project} -> ${project.dir}`);
  }
  pass(`wrote ${path.relative(repoRoot, appGluePath)}`);

  // Neither list is fatal, but neither is allowed to pass unnoticed: both mean
  // a locked tauri crate was left out of the Gradle project graph.
  for (const crate of noAndroidDir) {
    console.log(`  note: ${crate} has no Android directory, so it is not a Gradle project (this is the normal case for log/updater)`);
  }
  for (const crate of notUnpacked) {
    console.log(`  note: ${crate} is locked but not unpacked, so it could not be considered`);
  }
}

main();
