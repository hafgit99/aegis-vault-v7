/* Injects the website's legal copy into the app's twelve locales.
 *
 * The app had its own three-paragraph version of each document, and it was not
 * the same text as the one the website publishes. That is the worst possible
 * state for a legal document: a user agrees to one set of terms and is shown
 * another at first run, and neither side knows which is authoritative.
 *
 * The website's text is the one that ships, is reviewed, and already exists in
 * all twelve languages, so it is the source here rather than a rewrite. These
 * keys are copied verbatim -- no retyping, no per-locale editing -- which is the
 * only way twelve legal documents stay in agreement with each other.
 *
 * Run: node scripts/sync-legal-copy.cjs
 */
