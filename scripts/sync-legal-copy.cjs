function escapeSingle(value) {
  // Escape for a single-quoted JS string literal. A double quote inside the
  // value needs no escaping and must not be given one: escaping it would put a
  // stray backslash into every French and Italian description.
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, ' ');
}

let changed = 0;
for (const locale of LOCAL_ORDER) {
  const site = JSON.parse(fs.readFileSync(path.join(I18N, locale + '.json'), 'utf8'));
  const file = path.join(LOCALES, locale + '.ts');
  let source = fs.readFileSync(file, 'utf8');

  const handWritten = Object.entries(HAND_WRITTEN[locale] || {});
  if (handWritten.length === 0) throw new Error(`no hand-written keys for ${locale}`);

  const block = [
    MARKER_START,
    '  /* Generated by scripts/sync-legal-copy.cjs from the site dictionaries.',
    '   * Do not edit here: the website is the source, and re-run the script. */',
    ...KEY_ORDER.map((key) => {
      const value = site[key];
      if (typeof value !== 'string') {
        throw new Error(`${locale}.json has no ${key}`);
      }
      return `  'legal.${key}': '${escapeSingle(value)}',`;
    }),
    '  /* Settings card chrome, written here rather than taken from the site. */',
    ...handWritten.map(([key, value]) => `  '${key}': '${escapeSingle(value)}',`),
    MARKER_END,
  ].join('\n');

  const from = source.indexOf(MARKER_START);
  if (from !== -1) {
    const to = source.indexOf(MARKER_END, from);
    if (to === -1) throw new Error(`${locale}.ts: end marker missing`);
    source = source.slice(0, from) + block + source.slice(to + MARKER_END.length);
  } else {
    // Appended at the end of the translations object, which the locale files
    // close with `} as const;`.
    const end = source.lastIndexOf('} as const;');
    if (end === -1) throw new Error(`${locale}.ts: "} as const;" not found`);
    source = source.slice(0, end).replace(/\s*$/, '') + '\n\n' + block + '\n' + source.slice(end);
  }

  fs.writeFileSync(file, source, 'utf8');
  console.log(`${locale}.ts: ${KEY_ORDER.length} anahtar`);
  changed++;
}

console.log(`${changed} locale guncellendi.`);